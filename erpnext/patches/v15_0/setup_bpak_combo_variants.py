def execute():
	if not frappe.db.exists("Item", "BPAK-COMBO"):
		print("BPAK-COMBO template missing, skipping")
		return

	spool_map = {}
	for s in frappe.get_all("Item", filters={"variant_of": "OPT-SPOOL"}, fields=["name", "custom_шифр"]):
		m = re.search(r"-(\d{2})[СC]$", s.get("custom_шифр") or "")
		if m:
			spool_map[m.group(1)] = s.name

	n_ok = n_skip = n_err = 0
	for size, cam, batt, spool, code, desc in COMBOS:
		if cam == "00" or cam not in CAM or batt not in BATT_LABEL or spool not in SPOOL_INFO:
			n_skip += 1
			continue
		batt_label = BATT_LABEL[batt]
		spool_label = f"{spool} ({SPOOL_INFO[spool]})"
		try:
			v = create_variant(
				"BPAK-COMBO",
				{
					"Розмір рами": f'{size}"',
					"Тип камери": CAM[cam],
					"Батарея код": batt_label,
					"Котушка код": spool_label,
				},
			)
			v.flags.ignore_validate = True
			v.description = desc
			try:
				v.insert(ignore_permissions=True)
			except frappe.DuplicateEntryError:
				v = frappe.get_doc("Item", v.item_code)
				v.save(ignore_permissions=True)

			drone = f"BPLA-UKR-FO-{size}-{CAM_ABBR[int(cam)-1]}"
			batt_item = f"BATT-PACK-LI-{BATT_CFG[batt]}-{DEFAULT_CELL}"
			spool_item = spool_map.get(spool)

			items_list = []
			if frappe.db.exists("Item", drone):
				items_list.append({"item_code": drone, "qty": 1, "uom": "шт."})
			if frappe.db.exists("Item", batt_item):
				items_list.append({"item_code": batt_item, "qty": 1, "uom": "шт."})
			if spool_item:
				items_list.append({"item_code": spool_item, "qty": 1, "uom": "шт."})
			if frappe.db.exists("Item", DEFAULT_GS):
				items_list.append({"item_code": DEFAULT_GS, "qty": 1, "uom": "шт."})

			if not frappe.db.exists("Product Bundle", v.name):
				frappe.get_doc(
					{
						"doctype": "Product Bundle",
						"new_item_code": v.name,
						"description": desc,
						"items": items_list,
					}
				).insert(ignore_permissions=True)
			n_ok += 1
		except Exception as e:
			n_err += 1
			print(f"  WARN {code}: {e}")

	frappe.db.commit()
	print(f"OK={n_ok} SKIP={n_skip} ERR={n_err}")
